#!/usr/bin/env bash
# Builds one jlink runtime per target and writes into launcher/:
#   payload_<goos>_<goarch>.tgz   gzipped tar: planetiler.jar + runtime/
#   payload_<goos>_<goarch>.go    go:embed + deterministic id
# Go's _<goos>_<goarch>.go filename suffix means each target only compiles its own payload.
#
# Env overrides: PLANETILER_JAR, JDK_FEATURE, JDK_TAG, JDK_CACHE, JLINK_COMPRESS,
#                WANT_MODULES, TARGETS (e.g. TARGETS=mac:aarch64:darwin:arm64 for a quick local build)
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
LAUNCHER=$ROOT/launcher
JAR=${PLANETILER_JAR:-$ROOT/planetiler.jar}
JDK_FEATURE=${JDK_FEATURE:-25}
JDK_CACHE=${JDK_CACHE:-$ROOT/.jdk-cache}
# already gzipped, no need to compress again
JLINK_COMPRESS=${JLINK_COMPRESS:-zip-0}
WANT_MODULES=${WANT_MODULES:-"java.se jdk.compiler"}
# adoptium_os:adoptium_arch:goos:goarch
TARGETS=${TARGETS:-"linux:x64:linux:amd64 linux:aarch64:linux:arm64 mac:x64:darwin:amd64 mac:aarch64:darwin:arm64 windows:x64:windows:amd64"}
WORK=$ROOT/build/runtimes

for cmd in curl tar unzip; do
  command -v "$cmd" >/dev/null || { echo "missing tool: $cmd" >&2; exit 1; }
done
[ -f "$JAR" ] || { echo "jar not found: $JAR (set PLANETILER_JAR)" >&2; exit 1; }

sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum; else shasum -a 256; fi | cut -d' ' -f1; }

case "$(uname -s)" in
  Linux)  HOST_OS=linux ;;
  Darwin) HOST_OS=mac ;;
  *) echo "unsupported build host: $(uname -s) (use Linux, macOS, or WSL)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
  x86_64|amd64)  HOST_ARCH=x64 ;;
  aarch64|arm64) HOST_ARCH=aarch64 ;;
  *) echo "unsupported build arch: $(uname -m)" >&2; exit 1 ;;
esac

# Resolve ONE exact JDK release and use it for the host and every target,
# because jlink requires the host JDK and the target jmods to match exactly.
if [ -z "${JDK_TAG:-}" ]; then
  JDK_TAG=$(curl -fsSL "https://api.adoptium.net/v3/assets/latest/$JDK_FEATURE/hotspot?architecture=$HOST_ARCH&image_type=jdk&os=$HOST_OS&vendor=eclipse" \
    | grep -o '"release_name" *: *"[^"]*"' | sed -n '1s/.*: *"\(.*\)"/\1/p')
fi
[ -n "$JDK_TAG" ] || { echo "could not resolve JDK release from Adoptium" >&2; exit 1; }
echo "==> JDK release: $JDK_TAG (host $HOST_OS/$HOST_ARCH)"

jdk_home() { echo "$JDK_CACHE/$JDK_TAG/$1-$2/home"; }

fetch_jdk() { # adoptium_os adoptium_arch
  local os=$1 arch=$2 dir="$JDK_CACHE/$JDK_TAG/$1-$2" ext=tar.gz extracted
  if [ "$os" = windows ]; then ext=zip; fi
  if [ -d "$dir/home" ]; then return 0; fi

  echo "==> downloading JDK for $os/$arch" >&2
  rm -rf "$dir.tmp"; mkdir -p "$dir.tmp"
  curl -fsSL -o "$dir.tmp/jdk.$ext" \
    "https://api.adoptium.net/v3/binary/version/${JDK_TAG/+/%2B}/$os/$arch/jdk/hotspot/normal/eclipse"
  if [ "$ext" = zip ]; then unzip -q "$dir.tmp/jdk.zip" -d "$dir.tmp"
  else tar -xzf "$dir.tmp/jdk.tar.gz" -C "$dir.tmp"; fi
  rm "$dir.tmp/jdk.$ext"

  extracted=$(echo "$dir.tmp"/jdk-*)
  if [ "$os" = mac ]; then extracted="$extracted/Contents/Home"; fi
  mkdir -p "$dir"
  mv "$extracted" "$dir/home"
  rm -rf "$dir.tmp"

  # non-host JDKs are only needed for their jmods
  if [ "$os-$arch" != "$HOST_OS-$HOST_ARCH" ]; then
    find "$dir/home" -mindepth 1 -maxdepth 1 ! -name jmods -exec rm -rf {} +
  fi
}

fetch_jdk "$HOST_OS" "$HOST_ARCH"
HOST_HOME=$(jdk_home "$HOST_OS" "$HOST_ARCH")
[ -x "$HOST_HOME/bin/jlink" ] || { echo "host JDK incomplete; delete $JDK_CACHE and retry" >&2; exit 1; }

# keep only modules that exist in this JDK version
AVAILABLE=$("$HOST_HOME/bin/java" --list-modules | cut -d@ -f1)
MODS=""
for m in $WANT_MODULES; do
  if printf '%s\n' "$AVAILABLE" | grep -qx "$m"; then MODS="$MODS,$m"; else echo "    (skipping unavailable module $m)"; fi
done
MODS=${MODS#,}
echo "==> modules: $MODS"

JAR_HASH=$(sha256 < "$JAR")
rm -rf "$WORK" "$LAUNCHER"/payload_*
mkdir -p "$WORK"
trap 'rm -rf "$ROOT/build/runtimes"' EXIT

for t in $TARGETS; do
  IFS=: read -r os arch goos goarch <<< "$t"
  name=payload_${goos}_${goarch}
  fetch_jdk "$os" "$arch"

  stage=$WORK/$goos-$goarch
  mkdir -p "$stage"
  echo "==> $goos/$goarch: jlink"
  "$HOST_HOME/bin/jlink" \
    --module-path "$(jdk_home "$os" "$arch")/jmods" \
    --add-modules "$MODS" \
    --strip-debug --no-header-files --no-man-pages \
    --compress="$JLINK_COMPRESS" \
    --output "$stage/runtime"
  cp "$JAR" "$stage/planetiler.jar"

  # gzipped tar, jar first so --extract-jar can stop early
  COPYFILE_DISABLE=1 tar -czf "$LAUNCHER/$name.tgz" -C "$stage" planetiler.jar runtime

  id=$(printf '%s|%s|%s|%s|%s' "$JAR_HASH" "$JDK_TAG" "$MODS" "$goos" "$goarch" | sha256 | cut -c1-12)
  cat > "$LAUNCHER/$name.go" <<EOF
// Code generated by scripts/build-runtimes.sh; DO NOT EDIT.

package main

import _ "embed"

//go:embed $name.tgz
var payload []byte

const payloadID = "$id"
EOF
  rm -rf "$stage"
done

ls -lh "$LAUNCHER"/payload_*.tgz
